"""Input widgets and helpers shared by the tabs."""

from __future__ import annotations

from collections.abc import Callable, Iterable

from nicegui import ui
from nicegui.elements.mixins.value_element import ValueElement
from pydantic import ValidationError

from pyteslacoil.ui.theme import BAD
from pyteslacoil.units import length_in, length_symbol, length_to_meters

DEBOUNCE_MS = 300
"""Inputs report a new value once typing pauses for this long."""


def number_input(
    label: str,
    value: float | None,
    *,
    step: float,
    decimals: int = 3,
    minimum: float | None = None,
    maximum: float | None = None,
) -> ui.number:
    """A full-width number input that reports changes after typing pauses."""
    widget = ui.number(label=label, value=value, step=step, format=f"%.{decimals}f")
    if minimum is not None:
        widget.min = minimum
    if maximum is not None:
        widget.max = maximum
    return widget.classes("w-full").props(f"debounce={DEBOUNCE_MS}")


def length_input(label: str, value_m: float, unit: str, *, step: float, decimals: int = 3) -> ui.number:
    """A number input for a length stored in meters but shown in ``unit``."""
    return number_input(
        f"{label} ({length_symbol(unit)})", length_in(value_m, unit), step=step, decimals=decimals
    )


def value_of(widget: ui.number) -> float:
    """The widget's value, or :class:`ValueError` if the field is empty."""
    if widget.value is None:
        raise ValueError(f"{widget.props.get('label', 'A field')} is empty")
    return float(widget.value)


def meters(widget: ui.number, unit: str) -> float:
    """The widget's length value converted from ``unit`` to meters."""
    return length_to_meters(value_of(widget), unit)


def on_change(widgets: Iterable[ValueElement], handler: Callable[[], None]) -> None:
    """Call ``handler()`` whenever any of the value widgets changes."""
    for widget in widgets:
        widget.on_value_change(lambda _event: handler())


def describe_error(exc: Exception) -> str:
    """Readable text for a validation error."""
    if isinstance(exc, ValidationError):
        parts = []
        for error in exc.errors():
            msg = str(error["msg"]).removeprefix("Value error, ")
            field = ".".join(str(loc) for loc in error["loc"])
            parts.append(f"{field}: {msg}" if field else msg)
        return "; ".join(parts)
    return str(exc)


class ErrorLabel:
    """An inline, initially hidden error message inside a card."""

    def __init__(self) -> None:
        self.label = ui.label().classes("text-sm").style(f"color: {BAD};")
        self.label.set_visibility(False)

    def show(self, exc: Exception) -> None:
        self.label.text = f"Invalid input — {describe_error(exc)}"
        self.label.set_visibility(True)

    def clear(self) -> None:
        self.label.set_visibility(False)


def trusted_html(content: str) -> ui.html:
    """Render markup generated by this app itself (no user-supplied text)."""
    return ui.html(content, sanitize=False)
